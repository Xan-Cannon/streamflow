"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.
"""

import matplotlib.pyplot as plt
import numpy as np

L = 6
Ra = 170
Rb = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0,L,500)

V = np.zeros_like(x)
for i in range(len(x)):
  if x[i] < 2:
    V[i] = Ra - (q1 * x[i])
  elif 2 <= x[i] <= 4:
    V[i] = Ra - (q1 * 2) - P1
  elif x[i] > 4:
    V[i] = Ra - (q1 * 2) - P1 + Rb - (q2 * (x[i] - 4))

plt.figure(figsize=(8,4))
plt.plot(x,V, color='green')
plt.fill_between(x, V, color='green', alpha=0.3)
plt.title('Shear Diagram')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')
plt.grid(True)
plt.axhline(0, color='black', linewidth=1)
plt.show()

