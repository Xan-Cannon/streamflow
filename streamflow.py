import numpy as np
import csv

# open and read the CSV into to make python list
with open('2012-US-Birth-Rates.csv', 'r') as file:
    csv_reader = csv.reader(file)
    next(csv_reader) # this skips the header
    data_list = list(csv_reader)

# use array to convert the Python list into a Numpy 2D
data = np.array(data_list)

# slice the array
x = data[:, 0]
y_1 = data[:, 1].astype(float)

"""### Graphing the Data

Plot x and y_1 with the elements shown in the instructions in the code block below."""

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

x_dates = np.array(x, dtype='datetime64[D]')

# Define the target holiday dates for 2012
holidays = {
    "New Year's Day": '2012-01-01',
    "4th of July": '2012-07-04',
    "Halloween": '2012-10-31',
    "Thanksgiving": '2012-11-22',
    "Christmas": '2012-12-25'
}

# Create the plot
plt.figure(figsize=(12, 6))
plt.plot(x_dates, y_1, label='Births', color='blue', zorder=2)

# Adjust y-axis limits to leave plenty of blank space at the top and bottom
plt.ylim(3500, 5500)

# Annotate each holiday with a curved arrow adjusted for non-overlapping visibility
for name, date_str in holidays.items():
    target_date = np.datetime64(date_str)
    idx = np.where(x_dates == target_date)[0]
    if len(idx) > 0:
        idx_val = idx[0]
        birth_count = y_1[idx_val]

        # Use specific text offsets and directions to keep labels clean and clear of the blue line
        if name == "New Year's Day":
            xytext = (target_date + np.timedelta64(20, 'D'), birth_count - 300)
            rad = 0.3
        elif name == "4th of July":
            xytext = (target_date + np.timedelta64(22, 'D'), birth_count - 350)
            rad = 0.3
        elif name == "Halloween":
            # Shift left from previous -25D to -40D to give more room
            xytext = (target_date - np.timedelta64(40, 'D'), birth_count - 550)
            rad = 0.4
        elif name == "Thanksgiving":
            # Move this label to the left instead of the right (change +15D to -20D) to clear the sharp Christmas drop
            xytext = (target_date - np.timedelta64(20, 'D'), birth_count - 550)
            rad = 0.25
        elif name == "Christmas":
            xytext = (target_date - np.timedelta64(50, 'D'), birth_count - 200)
            rad = -0.3

        plt.annotate(
            name,
            xy=(target_date, birth_count),
            xytext=xytext,
            arrowprops=dict(
                arrowstyle="->",
                color='red',
                connectionstyle=f"arc3,rad={rad}",
                lw=1.5,
                zorder=3
            ),
            bbox=dict(boxstyle="round,pad=0.2", fc="white", ec="none", alpha=0.85, zorder=4),
            fontweight='bold',
            color='black',
            zorder=5
        )

plt.title('Average U.S. Daily Births with Holiday Annotations (2012)')
plt.xlabel('Date')
plt.ylabel('Births')
plt.grid(True)
plt.tight_layout()
plt.show()
